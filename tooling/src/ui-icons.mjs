import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { format } from 'oxfmt';
import { root } from './process.mjs';

const source = resolve(root, 'packages/ui/assets/lucide');
const manifest = JSON.parse(await readFile(resolve(source, 'provenance.json'), 'utf8'));
const shapes = {};
const icons = {};
for (const name of Object.keys(manifest.svgSha256).sort()) {
  const svg = await readFile(resolve(source, `${name}.svg`), 'utf8');
  const digest = createHash('sha256').update(svg).digest('hex');
  if (digest !== manifest.svgSha256[name]) throw new Error(`Lucide source drift: ${name}`);
  icons[name] = svg;
  shapes[name] = [
    ...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]+)\/>/g),
  ].map(([, kind, raw]) => [
    kind,
    Object.fromEntries(
      [...raw.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]),
    ),
  ]);
  if (!shapes[name].length) throw new Error(`Unsupported empty Lucide geometry: ${name}`);
}
if (
  (await readdir(source)).filter((name) => name.endsWith('.svg')).length !==
  Object.keys(icons).length
)
  throw new Error('Unregistered Lucide source');
const header =
  '// Generated by tooling/src/ui-icons.mjs from official Lucide 0.468.0 SVG. Do not edit.\n';
const outputs = [
  [
    'design/prototype/components/assets/provenance.json',
    JSON.stringify({
      ...manifest,
      usage:
        'Generated mirror of packages/ui/assets/lucide/provenance.json; NSH and both browser surfaces share these official sources.',
    }),
  ],
  [
    'packages/ui/src/icons.generated.ts',
    header +
      'export type LucideName = ' +
      Object.keys(shapes)
        .map((name) => JSON.stringify(name))
        .join(' | ') +
      ';\nexport const iconNodes: Record<string, [string, Record<string, string>][] > = ' +
      JSON.stringify(shapes) +
      ';\n',
  ],
  [
    'design/prototype/shared/icons.js',
    header + 'globalThis.HongguoIcons = ' + JSON.stringify(icons) + ';\n',
  ],
  [
    'design/prototype/components/assets/icons.js',
    header + 'export const icons = ' + JSON.stringify(icons) + ';\n',
  ],
];
for (const [file, content] of outputs) {
  const result = await format(file, content, { singleQuote: true, printWidth: 100 });
  if (result.errors.length) throw new Error(JSON.stringify(result.errors));
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== result.code)
      throw new Error(`Regenerate ${file}: pnpm ui:icons`);
  } else await writeFile(path, result.code);
}
console.log(
  `Lucide ${manifest.version}: ${Object.keys(icons).length} verified sources and synchronized outputs`,
);
